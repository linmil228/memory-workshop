string trim(string line) {
    size_t first = line.find_first_not_of(" \t");
    if (first == string::npos) {
        return "";
    }
    size_t last = line.find_last_not_of(" \t");
    return line.substr(first, last - first + 1);
}

int readChoice(int minChoice, int maxChoice) {
    string line;
    while (true) {
        cout << "Ваш выбор: ";
        if (!getline(cin, line)) {
            return -1;
        }
        line = trim(line);
        if (line.size() == 1 && line[0] >= '0' + minChoice && line[0] <= '0' + maxChoice) {
            return line[0] - '0';
        }
        cout << "Ошибка ввода. Введите одну цифру от " << minChoice << " до " << maxChoice << ".\n";
    }
}

bool waitEnter() {
    string line;
    while (true) {
        cout << "Нажмите Enter, чтобы продолжить: ";
        if (!getline(cin, line)) {
            return false;
        }
        if (trim(line).empty()) {
            return true;
        }
        cout << "Для продолжения нужна пустая строка.\n";
    }
}

