void showResult(int correct) {
    int score = correct * 10;
    cout << "\nПравильно: " << correct << " из 10\n";
    cout << "Баллы: " << score << " из 100\n";
    if (score >= 90) {
        cout << "Отличное понимание темы\n";
    } else if (score >= 70) {
        cout << "Уверенное понимание материала\n";
    } else if (score >= 50) {
        cout << "Базовые знания, рекомендуется повторение\n";
    } else {
        cout << "Стоит повторить материал\n";
    }
}

int askQuestion(const Question& question, int number) {
    cout << "\nЭтап: " << question.stage << "\n";
    cout << "Вопрос " << number << "/10. " << question.title << "\n";
    cout << question.text << "\n";
    if (!question.code.empty()) {
        cout << "\n" << question.code << "\n\n";
    }
    for (int i = 0; i < 3; i++) {
        cout << i + 1 << ") " << question.options[i] << "\n";
    }
    int answer = readChoice(1, 3);
    if (answer == -1) {
        return -1;
    }
    int correct = 0;
    if (answer == question.correctAnswer) {
        cout << "Верно\n";
        correct = 1;
    } else {
        cout << "Неверно\n";
    }
    cout << "Правильный ответ: " << question.correctAnswer << ") "
         << question.options[question.correctAnswer - 1] << "\n";
    cout << "Пояснение: " << question.explanation << "\n";
    if (!waitEnter()) {
        return -1;
    }
    return correct;
}

bool playGame() {
    int correct = 0;
    for (int i = 0; i < 10; i++) {
        int result = askQuestion(questions[i], i + 1);
        if (result == -1) {
            cout << "\nИгра прервана: ввод завершён.\n";
            return false;
        }
        correct += result;
    }
    showResult(correct);
    return true;
}

int main() {
    while (true) {
        showMenu();
        int choice = readChoice(0, 2);
        if (choice == -1 || choice == 0) {
            break;
        }
        if (choice == 2) {
            showRules();
        } else if (!playGame()) {
            break;
        }
    }
    cout << "До свидания!\n";
    return 0;
}
